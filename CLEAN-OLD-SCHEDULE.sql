-- تأكد من أن المعلمات جاهزات لإعادة إدخال الجدول

-- حذف الجلسات من جدول الطالبات
UPDATE students
SET schedule = '[]'::jsonb
WHERE school_id = (SELECT id FROM schools WHERE name = 'الابتدائية 382' LIMIT 1);

-- عرض النتيجة
SELECT 
  COUNT(*) as "عدد الطالبات",
  'تم تنظيف الجدول' as "الحالة"
FROM students
WHERE school_id = (SELECT id FROM schools WHERE name = 'الابتدائية 382' LIMIT 1);

