-- ========================================
-- تحديث أسماء الطلاب
-- ========================================
-- تغيير أسماء الطلاب بشكل دائم في قاعدة البيانات
-- ========================================

DO $$
DECLARE
  v_updated_count INTEGER := 0;
BEGIN
  RAISE NOTICE '🔄 بدء تحديث أسماء الطلاب...';
  RAISE NOTICE '════════════════════════════════════════';

  -- ========================================
  -- تغيير mohamed → إيلاف العتيبي
  -- ========================================
  UPDATE students
  SET 
    name = 'إيلاف العتيبي',
    initials = 'إ',
    updated_at = NOW()
  WHERE LOWER(name) = 'mohamed';

  IF FOUND THEN
    v_updated_count := v_updated_count + 1;
    RAISE NOTICE '✅ تم تحديث: mohamed → إيلاف العتيبي';
  ELSE
    RAISE NOTICE '⚠️ لم يتم العثور على طالبة باسم mohamed';
  END IF;

  -- ========================================
  -- تغيير selma → ليندا الغامدي
  -- ========================================
  UPDATE students
  SET 
    name = 'ليندا الغامدي',
    initials = 'ل',
    updated_at = NOW()
  WHERE LOWER(name) = 'selma';

  IF FOUND THEN
    v_updated_count := v_updated_count + 1;
    RAISE NOTICE '✅ تم تحديث: selma → ليندا الغامدي';
  ELSE
    RAISE NOTICE '⚠️ لم يتم العثور على طالبة باسم selma';
  END IF;

  -- ========================================
  -- رسالة نهائية
  -- ========================================
  RAISE NOTICE '════════════════════════════════════════';
  RAISE NOTICE '🎉 تم تحديث % اسم بنجاح!', v_updated_count;
  RAISE NOTICE '════════════════════════════════════════';

END $$;

-- ========================================
-- عرض الأسماء المحدثة
-- ========================================

SELECT 
  '📋 الطالبات المحدثات' as info;

SELECT 
  id,
  name as "الاسم",
  initials as "الحرف",
  grade as "الصف",
  age as "العمر",
  updated_at as "آخر تحديث"
FROM students
WHERE name IN ('إيلاف العتيبي', 'ليندا الغامدي')
ORDER BY name;

